-- Data Exploration --
-- Q1 — Number of restaurants in each city
SELECT
    city,
    COUNT(*) AS restaurant_count
FROM zomato_restaurants
GROUP BY city
ORDER BY restaurant_count DESC;

-- Q2 — Top 5 cities with highest number of orders
SELECT 
    r.city,
    COUNT(o.order_id) AS total_orders
FROM zomato_orders o
INNER JOIN zomato_restaurants r
    ON o.restaurant_id = r.restaurant_id
GROUP BY r.city
ORDER BY total_orders DESC
LIMIT 5;
-- Why join?

-- zomato_orders table-la order irukku, but city information zomato_restaurants table-la irukku.

-- Q3 — Calculate total revenue generated by each restaurant

-- total_cost order table-la irukku. So each restaurant-ku orders-la vandha total_cost-a SUM pannanum.
SELECT
    o.restaurant_id,
    SUM(o.total_cost) AS total_revenue
FROM zomato_orders o
GROUP BY o.restaurant_id
ORDER BY total_revenue DESC;

-- 4 — Average order amount for each city
SELECT
    r.city,
    AVG(o.total_cost) AS average_order_amount
FROM zomato_orders o
INNER JOIN zomato_restaurants r
    ON o.restaurant_id = r.restaurant_id
GROUP BY r.city
ORDER BY average_order_amount DESC;
-- Top 5 restaurants with highest total sales
SELECT
    o.restaurant_id,
    SUM(o.total_cost) AS total_sales
FROM zomato_orders o
GROUP BY o.restaurant_id
ORDER BY total_sales DESC
LIMIT 5;

